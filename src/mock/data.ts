// Helper to generate floor list according to specification:
// Subsolos (Subsolo 2, Subsolo 1), Térreo, 1º ao Nº
export function generateFloors(totalFloors: number, hasGround: boolean, basementCount: number): Floor[] {
  const floors: Floor[] = [];
  
  // Basements
  for (let b = basementCount; b >= 1; b--) {
    floors.push({
      id: `fl-sub-${b}`,
      name: `Subsolo ${b}`,
      level: -b,
      isActive: true,
    });
  }

  // Ground floor
  if (hasGround) {
    floors.push({
      id: 'fl-terreo',
      name: 'Térreo',
      level: 0,
      isActive: true,
    });
  }

  // Upper floors
  for (let f = 1; f <= totalFloors; f++) {
    floors.push({
      id: `fl-${f}`,
      name: `${f}º Andar`,
      level: f,
      isActive: true,
    });
  }

  return floors;
}

